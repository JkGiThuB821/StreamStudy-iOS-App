import Foundation

nonisolated struct LessonPlan: Codable, Equatable {

    nonisolated enum Source: String, Codable {
        case gemini     // generated by the Gemini API
        case local      // built on-device (no API key, or the AI call failed)
    }

    var summary: String
    var steps: [LessonStep]
    var source: Source
    var generatedAt: Date

    var totalMinutes: Int {
        steps.reduce(0) { $0 + $1.estimatedMinutes }
    }
}

nonisolated struct LessonStep: Codable, Equatable, Identifiable {

    nonisolated enum Kind: String, Codable, CaseIterable {
        case read, watch, practice, review

        var displayName: String {
            rawValue.capitalized
        }

        var sfSymbol: String {
            switch self {
            case .read: return "book.fill"
            case .watch: return "play.rectangle.fill"
            case .practice: return "hammer.fill"
            case .review: return "checkmark.seal.fill"
            }
        }
    }

    var id: UUID
    var title: String
    var objective: String
    var kind: Kind
    var estimatedMinutes: Int
    // LearningResource.id values, in the order they should be studied.
    var resourceIDs: [UUID]
    // Hands-on task for practice steps (may be empty for read/watch steps).
    var activity: String
    // A self-check question so the student knows they've understood the step.
    var checkpointQuestion: String
    // Only used for steps without resources (practice/review), which the
    // student ticks off themselves.
    var isManuallyCompleted: Bool
}
